'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_DIR||'playwright');
const root=path.resolve(__dirname,'..');
const data=JSON.parse(fs.readFileSync(path.join(root,'docs/fbs/latest-v071.json'),'utf8'));
let browser;
(async()=>{
  browser=await chromium.launch({headless:true,...(process.env.FBS_BROWSER_EXECUTABLE?{executablePath:process.env.FBS_BROWSER_EXECUTABLE}:{}),args:['--no-sandbox']});
  const context=await browser.newContext({acceptDownloads:true});
  const page=await context.newPage();const errors=[],external=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(!/^(file|blob|data):/.test(r.url()))external.push(r.url())});
  const summary=async(n,p)=>assert.equal(await page.locator('#game-summary').innerText(),`${n} games shown · ${p} with selected issue · ${n-p} explicit gaps`);
  for(const width of [1440,390]){
    await page.setViewportSize({width,height:1000});
    await page.goto(pathToFileURL(path.join(root,'docs/fbs/latest-v071.html')).href);
    await page.evaluate(async()=>await window.FBS_V071_READY);
    await summary(197,104);
    assert.equal(await page.locator('#metric-rows tr').count(),21);
    assert.equal(await page.locator('#provider-rows tr').count(),12);
    assert.equal(await page.locator('#coverage-rows tr').count(),3);
    assert.equal(await page.locator('#game-rows tr[data-game]').count(),30);
    assert.match(await page.locator('#refresh-accounting').innerText(),/104 completed, one failed and 38 were not attempted/);
    assert.match(await page.locator('#execution').innerText(),/No measured 12-core training throughput/);
    await page.selectOption('#layer','saved');await summary(197,135);
    await page.selectOption('#period','all');await summary(888,141);
    await page.selectOption('#layer','recovered_original');await summary(888,55);
    await page.selectOption('#period','final');await summary(691,55);
    await page.selectOption('#layer','latest');await summary(691,0);
    await page.selectOption('#period','refresh_gap');await summary(39,0);
    await page.locator('#search').fill('401866465');await summary(1,0);
    assert.match(await page.locator('#game-rows').innerText(),/fixture revision quarantined/);
    await page.locator('#search').fill('');await page.selectOption('#period','tbd');await summary(54,0);
    await page.selectOption('#period','all');await page.selectOption('#season','2024');await summary(920,0);
    await page.selectOption('#season','2025');await summary(934,0);
    await page.selectOption('#season','all');await summary(2742,104);
    await page.selectOption('#season','2026');await page.selectOption('#period','upcoming');await summary(197,104);
    await page.locator('#next').click();assert.equal(await page.locator('#page-status').innerText(),'Page 2 of 7');await page.locator('#previous').click();
    await page.locator('#game-rows button[data-detail]').first().focus();await page.keyboard.press('Enter');
    assert.equal(await page.locator('#game-detail').isVisible(),true);
    assert.match(await page.locator('#detail-content').innerText(),/CURRENT_ORIGIN_OUTLOOK|Current|GENUINELY_FUTURE_ISSUED_ROLLING/);
    assert.equal(await page.locator('#detail-content table').last().locator('tbody tr').count(),16);
    await page.keyboard.press('Escape');assert.equal(await page.locator('#game-detail').isVisible(),false);
    const [jsonDownload]=await Promise.all([page.waitForEvent('download'),page.locator('#report-download').click()]);
    assert.deepEqual(JSON.parse(fs.readFileSync(await jsonDownload.path(),'utf8')),data);
    const [csvDownload]=await Promise.all([page.waitForEvent('download'),page.locator('#download-view').click()]);
    const csv=fs.readFileSync(await csvDownload.path(),'utf8');assert.equal(csv.split('\r\n').length,199);
    assert.match(csv,/GENUINELY_FUTURE_ISSUED_ROLLING/);assert.match(csv,/V070_REFRESH_NOT_COMPLETED/);
    await page.locator('#search').fill('no-matching-fbs-game');await summary(0,0);assert.equal(await page.locator('#download-view').isDisabled(),true);await page.locator('#search').fill('');
    const layout=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth}));
    assert.ok(layout.width<=width,`Page overflow at ${width}: ${JSON.stringify(layout)}`);
    if(process.env.FBS_SCREENSHOTS){fs.mkdirSync(process.env.FBS_SCREENSHOTS,{recursive:true});await page.screenshot({path:path.join(process.env.FBS_SCREENSHOTS,`fbs-v071-${width}.png`),fullPage:true});}
  }
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  console.log(JSON.stringify({status:'PASS',viewports:[1440,390],games:data.games.length,issues:104,annualRows:21,providerRows:12,errors,externalRequests:external.length}));
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();});
